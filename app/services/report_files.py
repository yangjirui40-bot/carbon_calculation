def _pdf(texts: list, header: str, language: str = "zh") -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.cidfonts import UnicodeCIDFont
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    try:
        pdfmetrics.getFont("STSong-Light")
    except KeyError:
        pdfmetrics.registerFont(UnicodeCIDFont("STSong-Light"))

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=48, rightMargin=48, topMargin=56, bottomMargin=56)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("t", parent=styles["Title"], fontName="STSong-Light", fontSize=20, leading=26)
    head_style = ParagraphStyle("h", parent=styles["Heading2"], fontName="STSong-Light", fontSize=13, leading=18)
    body_style = ParagraphStyle("b", parent=styles["Normal"], fontName="STSong-Light", fontSize=10.5, leading=16)

    cell_style = ParagraphStyle("cell",parent=body_style,fontSize=9,leading=13,wordWrap="CJK")
    flow = [Paragraph(escape(header), title_style), Spacer(1, 14)]
    for section_title, rows in texts:
        flow.append(Paragraph(escape(section_title), head_style))
        flow.append(Spacer(1, 4))
        if rows:
            widths = [doc.width/len(rows[0])]*len(rows[0])
            table = Table([[Paragraph(escape(str(c)),cell_style) for c in row] for row in rows], colWidths=widths)
            table.setStyle(TableStyle([
                ("FONTNAME", (0, 0), (-1, -1), "STSong-Light"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d3ccbd")),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1eee5")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]))
            flow.append(table)
        flow.append(Spacer(1, 10))
    flow.append(Paragraph(_t(language, "disclaimer"), body_style))
    doc.build(flow)
    return buf.getvalue()


def iso14064_pdf(content: dict, language: str = "zh") -> bytes:
    company = content.get("company") or {}
    rows = [
        [_t(language, "company"), company.get("name", ""), company.get("industry", "")],
        [_t(language, "period"), content.get("reporting_period", ""), ""],
        [_t(language, "total"), f"{content.get('total_kgco2e')} kgCO2e", ""],
        [_t(language, "scope1"), content.get("scope_breakdown", {}).get("scope1", 0), "kgCO2e"],
        [_t(language, "scope2"), content.get("scope_breakdown", {}).get("scope2", 0), "kgCO2e"],
        [_t(language, "scope3"), content.get("scope_breakdown", {}).get("scope3", 0), "kgCO2e"],
        [_t(language, "standard"), content.get("standard", "ISO 14064-1"), ""],
        [_t(language, "generated"), content.get("generated_at", ""), ""],
    ]
    approval = content.get("internal_approval")
    labels = {"zh": ("企业内部关账", "未标记为已关账"), "en": ("Internal period close", "No closing designation"),
              "de": ("Interner Periodenabschluss", "Kein Abschlussvermerk"), "fr": ("Clôture interne", "Sans mention de clôture")}
    label, pending = labels.get(language, labels["en"])
    if approval:
        rows.append([label, f"{approval['period']} / v{approval['revision']}", approval["approved_at"]])
    else:
        rows.append([label, pending, ""])
    sections = [(_t(language,"overview"),rows)]
    boundary = content.get("boundary_snapshot")
    if boundary:
        sections.append((_t(language,"boundary"),[[f'{boundary["code"]} v{boundary["version"]}',boundary["consolidation"],boundary["note"]],
            *[[site["legal_entity"],site["name"],f'{site["share_ratio"]*100:g}%'] for site in boundary["sites"]]]))
    if coverage := content.get("scope_assessments"):
        sections.append(("Scope 3 · "+{"zh":"覆盖评估","en":"Coverage","de":"Abdeckung","fr":"Couverture"}.get(language,"Coverage"),
            [[line["category"],line["status"],line["rationale"]] for line in coverage]))
    if instruments := content.get("electricity_certificates"):
        label = {"zh":"绿电凭证覆盖电量（工厂实物量）","en":"Retired instruments (physical kWh)",
                 "de":"Entwertete Nachweise (kWh)","fr":"Certificats annulés (kWh)"}.get(language,"Electricity instruments (kWh)")
        sections.append((label, [[v["issuer"],v["serial"],v["record_no"],v["applied_kwh"]+" kWh"] for v in instruments]))
    return _pdf(sections, f"{company.get('name', '')} {_t(language, 'iso14064')}", language)


def pcf_pdf(content: dict, language: str = "zh") -> bytes:
    product = content.get("product") or {}
    rows = [
        [_t(language, "product"), product.get("product_name", ""), product.get("product_id", "")],
        [_t(language, "output"), product.get("output_quantity", ""), product.get("product_unit", "")],
        [_t(language, "upstream_total"), f"{content.get('total_upstream_emissions_kgco2e')} kgCO2e", ""],
        [_t(language, "unit_emissions"), f"{content.get('unit_product_emissions_kgco2e')} {content.get('unit_label', '')}", ""],
        [_t(language, "standard"), content.get("standard", "ISO 14067"), ""],
        [_t(language, "boundary"), content.get("boundary", ""), ""],
        [_t(language, "generated"), content.get("generated_at", ""), ""],
    ]
    item_rows = [[_t(language, x) for x in ("material", "amount", "factor", "emissions")]]
    for it in content.get("items", []):
        item_rows.append([
            it.get("material_name", ""), it.get("material_amount_cny", ""),
            it.get("factor_id", ""), it.get("emissions_kgco2e", ""),
        ])
    sections = [(_t(language, "overview"), rows), (_t(language, "bom"), item_rows)]
    if study := content.get("study"):
        rows.append([study["name"],f'v{study["version_no"]}',f'{study["start_on"]} – {study["end_on"]}'])
        sections.append((_t(language,"boundary"),[[study["boundary_note"]]]))
        allocations = content.get("production_allocations", [])
        if allocations:
            rows.append([_t(language,"total"),f'{content["total_study_emissions_kgco2e"]} kgCO2e',
                         f'{content["unit_study_emissions_kgco2e"]} {content.get("unit_label","")}'])
            sections.append(({"zh":"生产分摊","en":"Production allocation","de":"Produktionszuordnung","fr":"Allocation de production"}.get(language,"Production allocation"),
                [[line["record_no"],line["run_id"],f'{line["emissions_kgco2e"]} kgCO2e',line["reason"]] for line in allocations]))
    return _pdf(sections, f"{product.get('product_name', '')} {_t(language, 'pcf')}", language)


def iso14064_xml(content: dict) -> bytes:
    root = ET.Element("GHGInventory", {"standard": content.get("standard", "ISO 14064-1:2018"),
                                       "generated_at": content.get("generated_at", "")})
    company = content.get("company") or {}
    ET.SubElement(root, "Company", {"name": str(company.get("name", "")), "code": str(company.get("code", ""))})
    ET.SubElement(root, "ReportingPeriod").text = str(content.get("reporting_period", ""))
    if approval := content.get("internal_approval"):
        closing = ET.SubElement(root, "InternalPeriodClose", {
            "period": approval["period"], "revision": str(approval["revision"]),
            "approved_at": approval["approved_at"], "run_id": approval["run_id"],
        })
        ET.SubElement(closing, "DeclaredBoundary").text = approval["boundary"]
    if boundary := content.get("boundary_snapshot"):
        version = ET.SubElement(root,"BoundaryVersion", {"code": boundary["code"], "version": str(boundary["version"]),
                                                          "consolidation": boundary["consolidation"]})
        for site in boundary["sites"]:
            ET.SubElement(version,"Site",{"code":site["code"],"name":site["name"],"share_ratio":str(site["share_ratio"])})
    if coverage := content.get("scope_assessments"):
        categories = ET.SubElement(root,"Scope3Coverage")
        for item in coverage:
            ET.SubElement(categories,"Category",{"number":str(item["category"]),"status":item["status"]}).text = item["rationale"]
    if instruments := content.get("electricity_certificates"):
        register = ET.SubElement(root,"ElectricityInstruments",{"unit":"kWh","basis":"physical_consumption"})
        for item in instruments:
            ET.SubElement(register,"Allocation",{key:str(value) for key,value in item.items()})
    totals = ET.SubElement(root, "Emissions")
    ET.SubElement(totals, "Total", {"unit": "kgCO2e"}).text = str(content.get("total_kgco2e"))
    for scope in ("scope1", "scope2", "scope3"):
        ET.SubElement(totals, "Scope", {"id": scope}).text = str(content.get("scope_breakdown", {}).get(scope, 0))
    items = ET.SubElement(root, "Items")
    for it in content.get("items", []):
        ET.SubElement(items, "Item", {"category": str(it.get("category", "")),
                                      "factor_id": str(it.get("factor_id", "")),
                                      "factor_version": str(it.get("factor_version", ""))}
                      ).text = str(it.get("emissions_kgco2e"))
    ET.indent(root)
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


def pcf_xml(content: dict) -> bytes:
    """产品碳足迹平台交换数据包。"""
    root = ET.Element("ProductCarbonFootprint", {"standard": content.get("standard", "ISO 14067:2018"),
                                                 "profile": "carbonspeed_exchange_v1",
                                                 "assurance_status": "unverified",
                                                 "generated_at": content.get("generated_at", "")})
    product = content.get("product") or {}
    p = ET.SubElement(root, "Product")
    ET.SubElement(p, "ProductId").text = str(product.get("product_id", ""))
    ET.SubElement(p, "ProductName").text = str(product.get("product_name", ""))
    ET.SubElement(p, "OutputQuantity", {"unit": str(product.get("product_unit", ""))}).text = str(product.get("output_quantity", ""))
    em = ET.SubElement(root, "Emissions")
    ET.SubElement(root, "Usage").text = "Platform exchange. Not a validated CBAM submission or independent assurance."
    ET.SubElement(em, "TotalUpstream", {"unit": "kgCO2e"}).text = str(content.get("total_upstream_emissions_kgco2e"))
    ET.SubElement(em, "PerUnit", {"unit": str(content.get("unit_label", ""))}).text = str(content.get("unit_product_emissions_kgco2e"))
    if study := content.get("study"):
        rev = ET.SubElement(root,"StudyVersion",{"number":str(study["version_no"]), "digest":study["digest"]})
        ET.SubElement(rev,"BoundaryNote").text = study["boundary_note"]
        ET.SubElement(em,"TotalStudy",{"unit":"kgCO2e"}).text = str(content["total_study_emissions_kgco2e"])
        for item in content.get("production_allocations",[]):
            ET.SubElement(rev,"ProductionAllocation",{"run_id":item["run_id"],"record_no":item["record_no"],
                "share_ratio":str(item["share_ratio"]),"kgco2e":str(item["emissions_kgco2e"])}).text = item["reason"]
    cbam = ET.SubElement(root, "InstallationInputs")
    ET.SubElement(cbam, "InstallationName").text = str((content.get("cbam") or {}).get("installation", "") or "")
    ET.SubElement(cbam, "ProductionProcess").text = str((content.get("cbam") or {}).get("process", "") or "")
    ET.SubElement(cbam, "DirectEmissions", {"unit": "kgCO2e"}).text = str((content.get("cbam") or {}).get("direct_emissions", "") or "")
    ET.SubElement(cbam, "IndirectEmissions", {"unit": "kgCO2e"}).text = str((content.get("cbam") or {}).get("indirect_emissions", "") or "")
    ET.SubElement(cbam, "ElectricityConsumed", {"unit": "kWh"}).text = str((content.get("cbam") or {}).get("electricity_kwh", "") or "")
    et_b = ET.SubElement(root, "Boundary")
    ET.SubElement(et_b, "SystemBoundary").text = str(content.get("boundary", ""))
    items = ET.SubElement(root, "BomItems")
    for it in content.get("items", []):
        item = ET.SubElement(items, "Material")
        ET.SubElement(item, "Name").text = str(it.get("material_name", ""))
        if it.get("assembly_path"):
            ET.SubElement(item, "AssemblyPath").text = str(it["assembly_path"])
        ET.SubElement(item, "Amount", {"currency": "CNY"}).text = str(it.get("material_amount_cny"))
        ET.SubElement(item, "EmissionFactor", {"id": str(it.get("factor_id", "")),
                                               "version": str(it.get("factor_version", "")),
                                               "source": "demonstration" if it.get("is_demo") else "documented_factor"}).text = str(it.get("factor_kgco2e_per_cny"))
        ET.SubElement(item, "Emissions", {"unit": "kgCO2e"}).text = str(it.get("emissions_kgco2e"))
    ET.indent(root)
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


